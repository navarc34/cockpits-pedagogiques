#!/usr/bin/env node
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const base=path.resolve(__dirname,"..");
const data=JSON.parse(fs.readFileSync(path.join(base,"data/fr.json"),"utf8"));
const pilot=JSON.parse(fs.readFileSync(path.join(base,"data/pilotage.json"),"utf8"));
const {candidates,sessionId,audit}=require("../assets/trajectoire-evidence.js");
const byId=id=>pilot.fr.objectifs.find(x=>x.id===id);
const el=candidates(byId("fr-el-annuel"),data.seances,data.meta.arrete);
assert(el.length>=4,"Les séances EL 1/2 documentées doivent être proposées");
assert(el.some(x=>x.date==="2026-09-14"));
assert(el.some(x=>x.date==="2026-10-09"));
assert(el.every(x=>x.date<=data.meta.arrete));
assert.equal(new Set(el.map(x=>x.id)).size,el.length);
assert.equal(sessionId({date:"2026-10-09",time:"13:00"}),"fr-seance-2026-10-09-1300");
assert.equal(candidates(byId("fr-objets"),data.seances,data.meta.arrete).length,0);
assert.equal(candidates(byId("fr-negation"),data.seances,data.meta.arrete).length,0);
const bb=candidates(byId("fr-bb1"),data.seances,data.meta.arrete);
assert(bb.some(x=>x.date==="2026-11-09"));
const o=structuredClone(byId("fr-el-annuel"));
o.realisation.exclues.push({id:"preuve-test",date:el[0].date,type:"seance",reference:el[0].id});
assert(!candidates(o,data.seances,data.meta.arrete).some(x=>x.id===el[0].id));
o.realisation.exclues=[];
o.realisation.confirmees.push({id:"preuve-validee",date:el[0].date,type:"seance",reference:el[0].id});
assert(!candidates(o,data.seances,data.meta.arrete).some(x=>x.id===el[0].id));
assert.equal(audit(o,data.seances,data.meta.arrete).confirmes,1);
const invalid={...byId("fr-bb1"),reconnaissance:{mode:"regex",champs:["titre"],motif:"["}};
assert.throws(()=>candidates(invalid,data.seances,data.meta.arrete));
console.log("Preuves : correspondances, exclusion, validation, cutoff et règle manuelle OK");
